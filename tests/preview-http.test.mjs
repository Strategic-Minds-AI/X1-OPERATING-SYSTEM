import test from "node:test";
import assert from "node:assert/strict";
import {createWizardServer} from "../src/wizard-server.mjs";
test("ten localhost HTML routes require both approvals",async()=>{
 const server=createWizardServer();
 await new Promise((resolve,reject)=>server.once("error",reject).listen(4391,"127.0.0.1",resolve));
 const base="http://127.0.0.1:4391";
 const send=(path,payload)=>fetch(base+path,{method:"POST",headers:{"Origin":base,"Content-Type":"application/json"},body:JSON.stringify(payload)});
 try{
  const blocked=await send("/api/canary/build",{templateId:"app-admin-portal",objective:"Build a production administration portal"});
  assert.equal(blocked.status,422);
  const canaryResponse=await send("/api/canary/build",{templateId:"app-client-crm",objective:"Build an impressive local CRM with working lead search, export and statuses"});
  assert.equal(canaryResponse.status,200);
  const canary=await canaryResponse.json();
  assert.equal(canary.status,"REAL_SOURCE_COMPILED_LOCAL_PREFLIGHT_PASS");
  assert.equal(canary.independentQa,"NOT_RUN_BY_LOCAL_HTTP_SERVER");
  assert.equal(canary.productionAllowed,false);
  assert.ok(canary.manifest.files["app.js"]);
  const canaryPage=await fetch(base+canary.previewUrl);
  assert.equal(canaryPage.status,200);
  assert.match(canaryPage.headers.get("x-robots-tag"),/noindex/);
  assert.match(await canaryPage.text(),/Client Command Center/);
  const script=await fetch(base+canary.previewUrl.replace("index.html","app.js"));
  assert.equal(script.status,200);
  assert.match(await script.text(),/renderLeads/);
  assert.equal((await fetch(base+canary.previewUrl.replace("index.html","../manifest.json"))).status,404);
  const library=await fetch(base+"/templates");
  assert.equal(library.status,200);
  assert.match(await library.text(),/Start with the right blueprint/);
  const catalog=await (await fetch(base+"/api/templates")).json();
  assert.equal(catalog.summary.total,97);
  assert.equal(catalog.templates.length,97);
  const filtered=await (await fetch(base+"/api/templates?family=app")).json();
  assert.equal(filtered.templates.length,12);
  const doc=await fetch(base+"/api/templates/docs/app-client-crm");
  assert.equal(doc.status,200);
  assert.match(await doc.text(),/Client CRM and lead inbox/);
  const x=await send("/api/templates/draft",{id:"app-client-crm",values:{objective:"Help clients manage their leads"}});
  assert.equal(x.status,200);
  const planned=await x.json();
  assert.equal(planned.draft.status,"DRAFT_NOT_DISPATCHED");
  assert.equal(planned.draft.authorizedCostCents,0);
  assert.equal(planned.release,false);
  const bad=await send("/api/templates/draft",{id:"app-client-crm",values:{unsafe_control:"publish now"}});
  assert.equal(bad.status,422);
  const root=await fetch(base+"/");
  assert.equal(root.status,200);
  const listPage=await fetch(base+"/checklist");
  assert.equal(listPage.status,200);
  assert.match(await listPage.text(),/Every milestone/);
  const listing=await (await fetch(base+"/api/checklist")).json();
  assert.equal(listing.tasks.length,79);
  assert.equal(listing.instructions.backendDurableWorkerActive,false);
  const idle=await (await fetch(base+"/api/idle/policy")).json();
  assert.equal(idle.thresholdMs,600000);
  assert.deepEqual(idle.localOperations,["SYNTHETIC_CRM_CANARY_COMPILE","SYNTHETIC_STATIC_PREFLIGHT"]);
  assert.equal(idle.productionAuthorized,false);
  assert.equal(idle.serverSideDurableWorkerActive,false);
  const studio=await fetch(base+"/studio");
  assert.equal(studio.status,200);
  assert.match(await studio.text(),/Build with a conversation/);
  const preview=await fetch(base+"/api/studio/preview");
  assert.equal(preview.status,200);
  assert.match(await preview.text(),/noindex,nofollow/);
  const visual=await send("/api/studio/message",{message:"Set hero headline to The X1 Studio makes edits"});
  assert.equal(visual.status,200);
  const applied=await visual.json();
  assert.equal(applied.result.status,"APPLIED_TO_LOCAL_DRAFT");
  assert.equal(applied.state.plan.sections[0].content.headline,"The X1 Studio makes edits");
  const unbound=await (await send("/api/studio/message",{message:"Build a complete customer CRM and dashboard"})).json();
  assert.equal(unbound.result.status,"DRAFT_NOT_DISPATCHED");
  assert.equal(unbound.result.mission.jobId,null);
  assert.ok(unbound.recommendations.some(x=>x.id==="app-client-crm"));
  assert.ok(unbound.recommendations.every(x=>x.readiness==="DOCUMENTED_NOT_EXECUTED"));
  assert.equal(unbound.state.capabilities.x1LeaseExecution,"BLOCKED_AUTH_AND_SINGLE_SUPERVISOR");
  const before=await send("/api/generate",{});
  assert.equal(before.status,422);
  const state=await (await fetch(base+"/api/state")).json();
  const hash=state.plan.planHash;
  assert.equal((await send("/api/approve-markets",{planHash:hash,intent:"APPROVE_SYNTHETIC_MARKETS"})).status,200);
  assert.equal((await send("/api/approve-preview",{planHash:hash,intent:"APPROVE_TEN_LOCAL_PREVIEWS"})).status,200);
  const generated=await (await send("/api/generate",{})).json();
  assert.equal(generated.batch.sites.length,10);
  assert.equal(generated.receipt.staticGate,"PASS");
  for(const site of generated.batch.sites){
   const response=await fetch(base+site.localPath);
   assert.equal(response.status,200);
   assert.match(response.headers.get("x-robots-tag"),/noindex/);
  }
 }finally{await new Promise(resolve=>server.close(resolve));}
});
